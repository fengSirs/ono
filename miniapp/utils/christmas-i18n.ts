export function ct(
  lang: Lang,
  key: string,
  values: Record<string, string | number> = {},
) {
  const item = (words as any)[key];
  let text = item ? item[lang === "pt" ? 0 : lang === "en" ? 1 : 2] : key;
  for (const [k, v] of Object.entries(values))
    text = text.replaceAll("{" + k + "}", String(v));
  return text as string;
}

